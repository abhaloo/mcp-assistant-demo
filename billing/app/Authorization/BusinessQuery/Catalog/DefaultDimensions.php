    /**
     * Account type domain, read from Account::class's own constants (excludes
     * inherited constants like Model::CREATED_AT and non-string ones like
     * Account::PURCHASABLES).
     *
     * @return list<string>
     */
    private static function ledgerAccountTypes(): array
    {
        $types = [];
        foreach ((new ReflectionClass(Account::class))->getReflectionConstants() as $constant) {
            if ($constant->getDeclaringClass()->getName() !== Account::class) {
                continue;
            }
            if (is_string($constant->getValue())) {
                $types[] = $constant->getValue();
            }
        }
        sort($types);

        return $types;
    }
